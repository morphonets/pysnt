"""
Hard rules for the CURATED/EXTENDED class lists in pysnt modules

Uses dev/scripts/inventory/snt_inventory.json (generated by
dev/scripts/snt_inventory.py), so it needs no JVM. Skipped when the
inventory has not been generated
"""
import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / "dev" / "scripts" / "inventory" / "snt_inventory.json"
SYNC = ROOT / "dev" / "scripts" / "sync_module_lists.py"


def _load_sync():
    spec = importlib.util.spec_from_file_location("sync_module_lists", SYNC)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.mark.skipif(not INVENTORY.exists(), reason="SNT inventory not generated")
def test_listed_classes_are_public_and_curated_are_classes_or_interfaces():
    try:
        sync = _load_sync()
    except ModuleNotFoundError as e:
        pytest.skip(f"sync script needs tomllib/tomli: {e}")
    inventory = json.loads(INVENTORY.read_text(encoding="utf-8"))
    violations = sync.check(inventory, ROOT / "src" / "pysnt")
    assert not violations, "\n".join(violations)
